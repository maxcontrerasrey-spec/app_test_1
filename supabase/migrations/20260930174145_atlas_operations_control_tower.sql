create or replace function public.atlas_ops_apply_geofences()
returns trigger language plpgsql security definer set search_path = public
as $function$
declare
  fence record;
  prior record;
  current_m double precision;
  prior_m double precision;
  transition_name text;
  dispatch_key uuid;
  milestone_row record;
begin
  if new.vehicle_id is null then return new; end if;
  for fence in select * from public.atlas_ops_geofences where is_active loop
  select e.latitude, e.longitude into prior from public.atlas_ops_telemetry_events e
    where e.vehicle_id = new.vehicle_id and e.id <> new.id and e.observed_at < new.observed_at
    order by e.observed_at desc limit 1;
    if not found then continue; end if;
    if new.accuracy_m is not null and new.accuracy_m > fence.jitter_buffer_meters * 2 then continue; end if;
    current_m := 6371000 * 2 * asin(sqrt(
      power(sin(radians(new.latitude-fence.center_latitude)/2),2) +
      cos(radians(fence.center_latitude))*cos(radians(new.latitude))*power(sin(radians(new.longitude-fence.center_longitude)/2),2)
    ));
    prior_m := 6371000 * 2 * asin(sqrt(
      power(sin(radians(prior.latitude-fence.center_latitude)/2),2) +
      cos(radians(fence.center_latitude))*cos(radians(prior.latitude))*power(sin(radians(prior.longitude-fence.center_longitude)/2),2)
    ));
    transition_name := null;
    if prior_m >= fence.radius_meters + fence.jitter_buffer_meters and current_m <= fence.radius_meters - fence.jitter_buffer_meters then transition_name := 'enter';
    elsif prior_m <= fence.radius_meters - fence.jitter_buffer_meters and current_m >= fence.radius_meters + fence.jitter_buffer_meters then transition_name := 'exit';
    end if;
    if transition_name is null then continue; end if;
    if exists (
      select 1 from public.atlas_ops_geofence_events ge
      where ge.geofence_id=fence.id and ge.vehicle_id=new.vehicle_id
        and ge.occurred_at > new.observed_at - make_interval(secs => fence.min_transition_seconds)
    ) then continue; end if;
    insert into public.atlas_ops_geofence_events(geofence_id, telemetry_event_id, vehicle_id, transition, occurred_at)
    values (fence.id,new.id,new.vehicle_id,transition_name,new.observed_at) on conflict do nothing;
    select d.id into dispatch_key from public.atlas_ops_dispatches d
    where d.vehicle_id = new.vehicle_id and d.contract_id = fence.contract_id
      and d.planning_status = 'published' and d.service_date = (new.observed_at at time zone 'America/Santiago')::date
    order by d.planned_start_at desc limit 1;
    if dispatch_key is null then continue; end if;
    insert into public.atlas_ops_dispatch_events(dispatch_id,event_type,source,occurred_at,payload)
    values (dispatch_key,'geofence.'||transition_name,new.provider,new.observed_at,
      jsonb_build_object('geofence_id',fence.id,'geofence_code',fence.code,'telemetry_event_id',new.id));
    if fence.geofence_type = 'workshop' and transition_name = 'exit' then
      select * into milestone_row from public.atlas_ops_dispatch_milestones
      where dispatch_id=dispatch_key and code='WORKSHOP_EXIT' and status='pending' limit 1;
      if found then
        update public.atlas_ops_dispatch_milestones set status='completed',actual_at=new.observed_at where id=milestone_row.id;
        insert into public.atlas_ops_dispatch_events(dispatch_id,milestone_id,event_type,source,occurred_at,payload)
        values(dispatch_key,milestone_row.id,'milestone.completed',new.provider,new.observed_at,jsonb_build_object('evidence','geofence','telemetry_event_id',new.id));
      end if;
    end if;
  end loop;
  return new;
end;
$function$;
create trigger atlas_ops_telemetry_geofence after insert on public.atlas_ops_telemetry_events
for each row execute function public.atlas_ops_apply_geofences();

create or replace view public.atlas_ops_control_tower
with (security_invoker = true)
as
select d.id, d.contract_id, c.code as contract_code, d.service_date, d.shift, d.planned_start_at, d.acknowledged_at,
       t.name as service_name, d.driver_name_snapshot, d.vehicle_id, v.code as vehicle_code, v.plate,
       d.planning_status, d.execution_status,
       case when exists (select 1 from public.atlas_ops_alerts a where a.dispatch_id = d.id and a.status in ('open','acknowledged') and a.alert_type = 'critical') then 'critical'
            when exists (select 1 from public.atlas_ops_incidents i where i.dispatch_id=d.id and i.status in ('open','investigating') and i.severity='critical') then 'critical'
            when exists (select 1 from public.atlas_ops_alerts a where a.dispatch_id = d.id and a.status in ('open','acknowledged') and a.alert_type = 'at_risk') then 'at_risk'
            when exists (select 1 from public.atlas_ops_incidents i where i.dispatch_id=d.id and i.status in ('open','investigating') and i.severity='high') then 'at_risk'
            when exists (select 1 from public.atlas_ops_alerts a where a.dispatch_id = d.id and a.status in ('open','acknowledged') and a.alert_type = 'attention') then 'attention'
            when exists (select 1 from public.atlas_ops_dispatch_milestones m where m.dispatch_id=d.id and m.required and m.status='pending' and now()>=m.critical_at) then 'critical'
            when exists (select 1 from public.atlas_ops_dispatch_milestones m where m.dispatch_id=d.id and m.required and m.status='pending' and now()>=coalesce(m.warning_at,m.critical_at)) then 'attention'
            else 'green' end as risk_status
from public.atlas_ops_dispatches d
join public.contracts c on c.id = d.contract_id
left join public.atlas_ops_service_templates t on t.id = d.service_template_id
left join public.atlas_ops_vehicles v on v.id = d.vehicle_id;
revoke all on public.atlas_ops_control_tower from public, anon;
grant select on public.atlas_ops_control_tower to authenticated;

