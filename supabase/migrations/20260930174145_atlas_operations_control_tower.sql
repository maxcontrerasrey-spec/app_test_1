  select d.id, m.id,
         case when p_at >= m.critical_at then 'critical' else 'attention' end,
         case when p_at >= m.critical_at then 'Hito crítico vencido: ' || m.label else 'Hito próximo: ' || m.label end
  from public.atlas_ops_dispatches d
  join public.atlas_ops_dispatch_milestones m on m.dispatch_id = d.id
  where d.planning_status = 'published' and d.execution_status not in ('completed','failed','suspended')
    and m.required and m.status = 'pending' and p_at >= coalesce(m.warning_at, m.critical_at)
    and public.atlas_ops_can_edit_contract(actor, d.contract_id)
  on conflict (dispatch_id, milestone_id, alert_type) do update set message = excluded.message
  where public.atlas_ops_alerts.status = 'open';
  get diagnostics affected = row_count;
  update public.atlas_ops_alerts a set status = 'resolved', resolved_at = p_at,
    resolution_note = 'Hito completado o servicio cerrado automáticamente'
  from public.atlas_ops_dispatch_milestones m, public.atlas_ops_dispatches d
  where a.milestone_id = m.id and m.dispatch_id = d.id and a.status = 'open'
    and (m.status = 'completed' or d.execution_status in ('completed','failed','suspended','cancelled'))
    and public.atlas_ops_can_edit_contract(actor, d.contract_id);
  return affected;
end;
$function$;
