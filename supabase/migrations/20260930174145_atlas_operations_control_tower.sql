create or replace function public.atlas_ops_resolve_alert(p_alert_id uuid, p_note text)
returns void language plpgsql security definer set search_path = public
as $function$
declare actor uuid := auth.uid(); contract_key bigint;
dispatch_key uuid;
begin
  select d.contract_id, d.id into contract_key, dispatch_key from public.atlas_ops_alerts a join public.atlas_ops_dispatches d on d.id = a.dispatch_id where a.id = p_alert_id;
  if actor is null or not public.atlas_ops_can_edit_contract(actor, contract_key) then raise exception 'Sin permiso para resolver esta alerta.'; end if;
  update public.atlas_ops_alerts set status='resolved', resolved_at=now(), resolved_by=actor, resolution_note=nullif(trim(p_note),'')
  where id=p_alert_id and status <> 'resolved';
  if not found then raise exception 'Alerta no encontrada o ya resuelta.'; end if;
  insert into public.atlas_ops_dispatch_events(dispatch_id, event_type, source, actor_user_id, payload)
  values(dispatch_key, 'alert.resolved', 'coordinator', actor, jsonb_build_object('alert_id', p_alert_id, 'note', nullif(trim(p_note),'')));
end;
$function$;
