-- New authorization boundary; contract editors remain explicit and row scoped.
create or replace function public.atlas_ops_is_current_super_admin()
returns boolean language sql stable security definer set search_path = public
as $$
  select auth.uid() is not null and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.status = 'active' and p.is_super_admin = true
  )
$$;
revoke all on function public.atlas_ops_is_current_super_admin() from public, anon;
grant execute on function public.atlas_ops_is_current_super_admin() to authenticated;

create or replace function public.atlas_ops_can_manage(requested_user_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select requested_user_id is not null
     and auth.uid() is not null
     and auth.uid() = requested_user_id
     and public.atlas_ops_is_current_super_admin()
$$;

create or replace function public.atlas_ops_can_edit_contract(requested_user_id uuid, requested_contract_id bigint)
returns boolean language plpgsql stable security definer set search_path = public
as $function$
begin
  if requested_user_id is null or requested_contract_id is null or auth.uid() is null then return false; end if;
  if auth.uid() <> requested_user_id or not public.atlas_ops_is_current_super_admin() then return false; end if;
  return exists(select 1 from public.contracts c where c.id = requested_contract_id and c.is_active);
end;
$function$;

revoke all on function public.atlas_ops_can_manage(uuid) from public, anon;
revoke all on function public.atlas_ops_can_edit_contract(uuid, bigint) from public, anon;
grant execute on function public.atlas_ops_can_manage(uuid) to authenticated;
grant execute on function public.atlas_ops_can_edit_contract(uuid, bigint) to authenticated;

do $$
declare t text; predicate text;
begin
  foreach t in array array[
    'atlas_ops_contract_editors','atlas_ops_service_templates','atlas_ops_vehicles','atlas_ops_dispatches',
    'atlas_ops_milestone_templates','atlas_ops_dispatch_milestones','atlas_ops_dispatch_events',
    'atlas_ops_driver_accounts','atlas_ops_telemetry_vehicle_bindings','atlas_ops_telemetry_events',
    'atlas_ops_geofences','atlas_ops_geofence_events','atlas_ops_alerts','atlas_ops_incidents'
  ] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on table public.%I from public, anon, authenticated', t);
    execute format('grant select on table public.%I to authenticated', t);
    predicate := case t
      when 'atlas_ops_contract_editors' then 'public.atlas_ops_is_current_super_admin()'
      when 'atlas_ops_service_templates' then 'public.atlas_ops_can_edit_contract((select auth.uid()), contract_id)'
      when 'atlas_ops_vehicles' then 'public.atlas_ops_can_manage((select auth.uid()))'
      when 'atlas_ops_dispatches' then 'public.atlas_ops_can_edit_contract((select auth.uid()), contract_id)'
      when 'atlas_ops_milestone_templates' then 'public.atlas_ops_can_edit_contract((select auth.uid()), contract_id)'
      when 'atlas_ops_driver_accounts' then 'public.atlas_ops_is_current_super_admin()'
      when 'atlas_ops_telemetry_vehicle_bindings' then 'public.atlas_ops_is_current_super_admin()'
      when 'atlas_ops_telemetry_events' then 'public.atlas_ops_is_current_super_admin()'
      when 'atlas_ops_geofences' then 'public.atlas_ops_is_current_super_admin()'
      when 'atlas_ops_geofence_events' then 'public.atlas_ops_is_current_super_admin()'
      else format('exists (select 1 from public.atlas_ops_dispatches d where d.id = %I.dispatch_id and public.atlas_ops_can_edit_contract((select auth.uid()), d.contract_id))', t)
    end;
    execute format('create policy %I on public.%I for select to authenticated using (%s)', t || '_select', t, predicate);
  end loop;
end $$;

